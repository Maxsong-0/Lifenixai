const translations: Record<Locale, TranslationDict> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

/* ═══════════════ Context ═══════════════ */
interface LanguageContextValue {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, fallback?: string) => string;
  dateLocale: string; // "zh-CN" | "en-US" for toLocaleString
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be inside LanguageProvider");
  return ctx;
}

/** Shorthand hook that returns just the t function */
export function useT() {
  return useLanguage().t;
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleRaw] = useState<Locale>(() => {
    try {
      return (localStorage.getItem("lifenix-lang") as Locale) || "zh-CN";
    } catch {
      return "zh-CN";
    }
  });

  const setLocale = useCallback((l: Locale) => {
    setLocaleRaw(l);
    try { localStorage.setItem("lifenix-lang", l); } catch { /* */ }
  }, []);

  const t = useCallback(
    (key: string, fallback?: string): string => {
      return translations[locale]?.[key] ?? fallback ?? key;
    },
    [locale]
  );

  const dateLocale = translations[locale]?.["date.locale"] || locale;

  return (
    <LanguageContext.Provider value={{ locale, setLocale, t, dateLocale }}>
      {children}
    </LanguageContext.Provider>
  );
}
